// Regenerates lib/hub/scripts.ts from resources/bin/qutty-mcp and resources/bin/qutty-hook.
// The packaged app cannot read files outside its module graph, so the shims ship as string
// constants; tests/hub_scripts_test.ts fails when the two drift. Run after editing a shim:
//
//   deno run --allow-read --allow-write scripts/gen-hub-scripts.ts

const root = new URL("../", import.meta.url);
const read = (name: string) =>
  Deno.readTextFileSync(new URL(`resources/bin/${name}`, root));

/** The generated module's text. */
export function hubScriptsModule(mcp: string, hook: string): string {
  return [
    "// Generated by scripts/gen-hub-scripts.ts from resources/bin/: do not edit by hand.",
    "",
    "/** resources/bin/qutty-mcp */",
    `export const QUTTY_MCP_SCRIPT = ${JSON.stringify(mcp)};`,
    "",
    "/** resources/bin/qutty-hook */",
    `export const QUTTY_HOOK_SCRIPT = ${JSON.stringify(hook)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  Deno.writeTextFileSync(
    new URL("lib/hub/scripts.ts", root),
    hubScriptsModule(read("qutty-mcp"), read("qutty-hook")),
  );
}
