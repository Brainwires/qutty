// Regenerates lib/hub/scripts.ts from resources/bin/qutty-mcp and resources/bin/qutty-hook, and
// lib/hub/shell-scripts.ts from resources/bin/qutty-agent and resources/shell/qutty.{zsh,bash}.
// The packaged app cannot read files outside its module graph, so the shims ship as string
// constants; tests/hub_launch_test.ts and tests/shell_agent_test.ts fail when they drift. Run
// after editing a shim:
//
//   deno run --allow-read --allow-write scripts/gen-hub-scripts.ts

const root = new URL("../", import.meta.url);
const read = (name: string) =>
  Deno.readTextFileSync(new URL(`resources/bin/${name}`, root));
const readShell = (name: string) =>
  Deno.readTextFileSync(new URL(`resources/shell/${name}`, root));

/** The generated module's text. */
export function hubScriptsModule(mcp: string, hook: string): string {
  return [
    "// Generated by scripts/gen-hub-scripts.ts from resources/bin/: do not edit by hand.",
    "",
    "/** resources/bin/qutty-mcp */",
    `export const QUTTY_MCP_SCRIPT = ${JSON.stringify(mcp)};`,
    "",
    "/** resources/bin/qutty-hook */",
    `export const QUTTY_HOOK_SCRIPT = ${JSON.stringify(hook)};`,
    "",
  ].join("\n");
}

/** The shell agent's generated module: its client and the two shell plugins. */
export function shellScriptsModule(
  agent: string,
  zsh: string,
  bash: string,
): string {
  return [
    "// Generated by scripts/gen-hub-scripts.ts from resources/: do not edit by hand.",
    "",
    "/** resources/bin/qutty-agent */",
    `export const QUTTY_AGENT_SCRIPT = ${JSON.stringify(agent)};`,
    "",
    "/** resources/shell/qutty.zsh */",
    `export const QUTTY_ZSH_PLUGIN = ${JSON.stringify(zsh)};`,
    "",
    "/** resources/shell/qutty.bash */",
    `export const QUTTY_BASH_PLUGIN = ${JSON.stringify(bash)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  Deno.writeTextFileSync(
    new URL("lib/hub/scripts.ts", root),
    hubScriptsModule(read("qutty-mcp"), read("qutty-hook")),
  );
  Deno.writeTextFileSync(
    new URL("lib/hub/shell-scripts.ts", root),
    shellScriptsModule(
      read("qutty-agent"),
      readShell("qutty.zsh"),
      readShell("qutty.bash"),
    ),
  );
}
