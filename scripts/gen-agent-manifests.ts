// Regenerates lib/agent/detect/bundled.ts from resources/agent-detection/*.json, the bundled agent
// detection manifests (lib/agent/detect/manifest.ts). The packaged app cannot read files outside
// its module graph, so they ship as string constants; tests/agent_detect_test.ts fails when they
// drift. Run after editing a manifest:
//
//   deno run --allow-read --allow-write scripts/gen-agent-manifests.ts && deno fmt lib/agent/detect

const root = new URL("../", import.meta.url);
const dir = new URL("resources/agent-detection/", root);

/** The manifests' files, by name, in name order. */
export function readManifestFiles(): [string, string][] {
  const out: [string, string][] = [];
  for (const e of Deno.readDirSync(dir)) {
    if (e.isFile && e.name.endsWith(".json")) {
      out.push([e.name, Deno.readTextFileSync(new URL(e.name, dir))]);
    }
  }
  return out.sort(([a], [b]) => a.localeCompare(b));
}

/** The generated module's text. */
export function bundledModule(files: readonly [string, string][]): string {
  return [
    "// Generated by scripts/gen-agent-manifests.ts from resources/agent-detection/: do not edit by",
    "// hand.",
    "",
    "/** The bundled agent detection manifests, as JSON text, by file name. */",
    "export const BUNDLED_MANIFESTS: Record<string, string> = {",
    ...files.map(([name, text]) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`
    ),
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  Deno.writeTextFileSync(
    new URL("lib/agent/detect/bundled.ts", root),
    bundledModule(readManifestFiles()),
  );
}
